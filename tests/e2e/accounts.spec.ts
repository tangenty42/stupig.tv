import { randomInt, randomUUID } from 'node:crypto'
import { expect } from '@playwright/test'
import { login, logout, ready, test } from '../support/e2e-browser'

test('account lifecycle: registration, birthday, avatar, password and logout', async ({ page }) => {
  test.setTimeout(240_000)
  const username = `e2e${randomUUID().slice(0, 8)}`
  const phone = `18${randomInt(1_000_000_000).toString().padStart(9, '0')}`
  await page.goto('/')
  await ready(page)
  await page.getByRole('button', { name: '登录 / 注册', exact: true }).click()
  await page.getByRole('tab', { name: '注册', exact: true }).click()
  const form = page.locator('#register-form')
  await form.locator('input[name="username"]').fill(username)
  await form.locator('input[name="phone"]').fill(phone)
  await form.locator('input[name="password"]').fill('E2eRegister!842')
  await form.locator('input[name="confirm_password"]').fill('E2eRegister!842')
  await form.locator('input[name="confirm_password"]').press('Tab')
  const sent = page.waitForResponse(response => response.url().includes('auth.sendOtp') && response.request().method() === 'POST')
  await form.getByRole('button', { name: '发送', exact: true }).click()
  expect((await sent).ok()).toBe(true)
  await expect(form.getByRole('button')).toBeDisabled()
  await form.locator('input[autocomplete="one-time-code"]').fill('000000')
  await page.getByRole('button', { name: '立即注册', exact: true }).click()
  await expect(page.getByText('验证码不正确或已过期', { exact: true })).toBeVisible()
  await form.locator('input[autocomplete="one-time-code"]').fill('123456')
  await page.getByRole('button', { name: '立即注册', exact: true }).click()
  await expect(page.getByRole('button', { name: `用户菜单：${username}`, exact: true })).toBeVisible()
  await page.reload()
  await ready(page)
  await expect(page.getByRole('button', { name: `用户菜单：${username}`, exact: true })).toBeVisible()

  await test.step('birthday survives a hard reload', async () => {
    await page.getByRole('button', { name: `用户菜单：${username}`, exact: true }).hover()
    await page.getByRole('link', { name: '我的主页', exact: true }).click()
    await expect(page).toHaveURL(/\/u\/\d+$/)
    await page.getByRole('button', { name: '编辑', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: '更新生日', exact: true })
    await dialog.getByRole('gridcell').filter({ hasText: /^15$/ }).click()
    await dialog.getByRole('button', { name: '确定', exact: true }).click()
    await expect(dialog).toBeHidden()
    await page.reload()
    await ready(page)
    await page.getByRole('button', { name: '编辑', exact: true }).click()
    await expect(dialog.locator('[aria-selected="true"]')).toHaveText('15')
    await dialog.getByRole('button', { name: '取消', exact: true }).click()
  })

  await test.step('avatar is cropped, uploaded and decoded after reload', async () => {
    const png = await page.evaluate(() => {
      const canvas = document.createElement('canvas')
      canvas.width = canvas.height = 192
      const drawing = canvas.getContext('2d')!
      drawing.fillStyle = '#16a34a'
      drawing.fillRect(0, 0, 192, 192)
      drawing.fillStyle = '#facc15'
      drawing.fillRect(48, 48, 96, 96)
      return canvas.toDataURL('image/png').split(',')[1]!
    })
    await page.locator('input[type="file"]').setInputFiles({ name: 'e2e-avatar.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') })
    const dialog = page.getByRole('dialog', { name: '调整', exact: true })
    await expect(dialog.getByRole('img', { name: '待裁剪头像', exact: true }).first()).toBeVisible()
    await dialog.getByRole('button', { name: '确定', exact: true }).click()
    await expect(dialog).toBeHidden()
    const avatar = page.locator('main').getByRole('img', { name: `${username} 的头像`, exact: true })
    await expect(avatar).toHaveAttribute('src', /\/avatar\/[^/?]+\.jpg\?version=/)
    const source = await avatar.getAttribute('src')
    await page.reload()
    await ready(page)
    await expect(avatar).toHaveAttribute('src', source!)
    await expect.poll(() => avatar.evaluate(image => (image as HTMLImageElement).complete && (image as HTMLImageElement).naturalWidth === 512)).toBe(true)
    await page.locator('main').getByRole('button', { name: '删除', exact: true }).click()
    await page.getByRole('button', { name: '确定', exact: true }).click()
    await expect(avatar).toHaveCount(0)
    await page.reload()
    await ready(page)
    await expect(avatar).toHaveCount(0)
  })

  await test.step('password change rejects the wrong old password', async () => {
    const form = page.locator('form').filter({ has: page.locator('input[name="old_password"]') })
    await form.locator('input[name="old_password"]').fill('WrongPassword!842')
    await form.locator('input[name="new_password"]').fill('E2eUpdated!953')
    await form.locator('input[name="confirm_new_password"]').fill('E2eUpdated!953')
    await form.locator('input[name="confirm_new_password"]').press('Tab')
    await form.getByRole('button', { name: '修改', exact: true }).click()
    await expect(page.getByText('旧密码不正确', { exact: true })).toBeVisible()
    await form.locator('input[name="old_password"]').fill('E2eRegister!842')
    await form.getByRole('button', { name: '修改', exact: true }).click()
    await expect(page.getByText('密码修改成功！', { exact: true })).toBeVisible()
  })

  await test.step('logout clears authentication and only the new password works', async () => {
    await logout(page)
    await page.reload()
    await ready(page)
    await expect(page.getByRole('button', { name: '登录 / 注册', exact: true })).toBeVisible()
    await page.getByRole('button', { name: '登录 / 注册', exact: true }).click()
    const form = page.locator('#login-password-form')
    await form.locator('input[name="username_or_phone"]').fill(username)
    await form.locator('input[type="password"]').fill('E2eRegister!842')
    await form.locator('input[type="password"]').press('Tab')
    await page.getByRole('button', { name: '立即登录', exact: true }).click()
    await expect(page.getByText('用户名或密码错误', { exact: true })).toBeVisible()
    await login(page, username, 'E2eUpdated!953')
    await logout(page)
  })
})

test('phone login sends a code, enforces cooldown and rejects incorrect codes', async ({ page }) => {
  await page.goto('/')
  await ready(page)
  await page.getByRole('button', { name: '登录 / 注册', exact: true }).click()
  await page.getByRole('button', { name: '手机验证码登录', exact: true }).click()
  const form = page.locator('#login-phone-form')
  await form.locator('input[name="phone"]').fill('19000000000')
  await form.locator('input[name="phone"]').press('Tab')
  const sent = page.waitForResponse(response => response.url().includes('auth.sendOtp') && response.request().method() === 'POST')
  await form.getByRole('button', { name: '发送', exact: true }).click()
  expect((await sent).ok()).toBe(true)
  await expect(form.getByRole('button')).toBeDisabled()
  const repeated = await page.request.post('/api/trpc/auth.sendOtp', { data: { phone: '19000000000', purpose: 'login' } })
  expect(repeated.status()).toBe(429)
  await form.locator('input[autocomplete="one-time-code"]').fill('000000')
  await page.getByRole('button', { name: '立即登录', exact: true }).click()
  await expect(page.getByText('验证码不正确或已过期', { exact: true })).toBeVisible()
  await form.locator('input[autocomplete="one-time-code"]').fill('123456')
  await page.getByRole('button', { name: '立即登录', exact: true }).click()
  await expect(page.getByRole('button', { name: '用户菜单：user', exact: true })).toBeVisible()
  await page.reload()
  await ready(page)
  await expect(page.getByRole('button', { name: '用户菜单：user', exact: true })).toBeVisible()
  await logout(page)
})
