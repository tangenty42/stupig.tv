import { expect } from '@playwright/test'
import { otp_login_account, password_setup_account } from '../support/e2e-accounts'
import { login, logout, ready, test } from '../support/e2e-browser'

test('phone login enforces code rules and allows a passwordless user to skip setup', async ({ page }) => {
  await page.goto('/')
  await ready(page)
  await page.getByRole('button', { name: '登录 / 注册', exact: true }).click()
  const password_form = page.locator('#login-password-form')
  await password_form.locator('input[name="username_or_phone"]').fill(otp_login_account.username)
  await password_form.locator('input[name="password"]').fill('Previous!829')
  await page.getByRole('button', { name: '立即登录', exact: true }).click()
  await expect(page.getByText('尚未设置密码，请使用手机号验证码登录', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '手机验证码登录', exact: true }).click()
  const form = page.locator('#login-phone-form')
  await form.locator('input[name="phone"]').fill(otp_login_account.phone)
  await form.locator('input[name="phone"]').press('Tab')
  const sent = page.waitForResponse(response => response.url().includes('auth.sendOtp') && response.request().method() === 'POST')
  await form.getByRole('button', { name: '发送', exact: true }).click()
  expect((await sent).ok()).toBe(true)
  await expect(form.getByRole('button')).toBeDisabled()
  const repeated = await page.request.post('/api/trpc/auth.sendOtp', { data: { phone: otp_login_account.phone, purpose: 'login' } })
  expect(repeated.status()).toBe(429)
  await form.locator('input[autocomplete="one-time-code"]').fill('000000')
  await page.getByRole('button', { name: '立即登录', exact: true }).click()
  await expect(page.getByText('验证码不正确或已过期', { exact: true })).toBeVisible()
  await form.locator('input[autocomplete="one-time-code"]').fill('123456')
  await page.getByRole('button', { name: '立即登录', exact: true }).click()
  const menu = page.getByRole('button', { name: `用户菜单：${otp_login_account.username}`, exact: true })
  await expect(menu).toBeVisible()
  const setup = page.getByRole('dialog', { name: '设置密码' })
  await expect(setup).toBeVisible()
  await expect(form).toBeHidden()
  await expect(setup.getByRole('button', { name: '稍后再说', exact: true })).toHaveCount(0)
  await setup.getByRole('button', { name: '关闭', exact: true }).click()
  await expect(setup).toBeHidden()
  await page.reload()
  await ready(page)
  await expect(menu).toBeVisible()
})

test('lets an SMS-authenticated user set a password and log in with it', async ({ page }) => {
  await page.goto('/')
  await ready(page)
  await page.getByRole('button', { name: '登录 / 注册', exact: true }).click()
  await page.getByRole('button', { name: '手机验证码登录', exact: true }).click()
  const form = page.locator('#login-phone-form')
  await form.locator('input[name="phone"]').fill(password_setup_account.phone)
  await form.locator('input[name="phone"]').press('Tab')
  const sent = page.waitForResponse(response => response.url().includes('auth.sendOtp') && response.request().method() === 'POST')
  await form.getByRole('button', { name: '发送', exact: true }).click()
  expect((await sent).ok()).toBe(true)
  await form.locator('input[autocomplete="one-time-code"]').fill('123456')
  await page.getByRole('button', { name: '立即登录', exact: true }).click()
  const setup = page.getByRole('dialog', { name: '设置密码' })
  await expect(setup).toBeVisible()
  const new_password = `${'春风夏雨秋月冬雪'.repeat(3)}山`
  await setup.getByLabel('新密码', { exact: true }).fill(new_password)
  await setup.getByLabel('确认新密码', { exact: true }).fill(new_password)
  await setup.getByRole('button', { name: '设置密码', exact: true }).click()
  await expect(setup).toBeHidden()
  await logout(page)
  await login(page, password_setup_account.username, new_password)
})
