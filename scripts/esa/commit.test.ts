import type { ExecFileOptions } from 'node:child_process'
import { existsSync, readdirSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { commit_source, create_commit_description, parse_commit_version, source_fingerprint } from './commit'
import { load_publish_config } from './config'

const { exec } = vi.hoisted(() => ({ exec: vi.fn() }))
vi.mock('node:child_process', () => ({ execFile: exec }))
afterEach(() => vi.unstubAllEnvs())

describe('pinned ESA CLI output contract', () => {
  it.each(['dev', 'prod'] as const)('uses compact %s cloud metadata while preserving the unique run identity', (environment) => {
    const uuid = 'c0ad047b-fbfe-4725-b295-d43012181152'
    const source = Buffer.from('export default {}\n')
    const description = create_commit_description(environment, `2026-10-25T06-01-45-871Z-${uuid}`, source)
    expect(description.length).toBeLessThanOrEqual(64)
    expect(description).toContain(environment === 'dev' ? `dev-${source_fingerprint(source)}-` : 'stupig-prod-')
    expect(description).toContain(uuid)
    expect(create_commit_description(environment, '2026-10-25T06-01-45-871Z-00000000-0000-0000-0000-000000000000', source)).not.toBe(description)
  })

  it('compares source fingerprints across line-ending conventions', () => {
    expect(source_fingerprint(Buffer.from('a\r\nb\r\n'))).toBe(source_fingerprint(Buffer.from('a\nb\n')))
    expect(source_fingerprint(Buffer.from('a\nb\n'))).not.toBe(source_fingerprint(Buffer.from('a\nc\n')))
  })

  it('extracts exactly the version generated by this invocation', () => {
    expect(parse_commit_version('Routine exists\n✓ Version generated: 184875929281435\nCode version 184875929281435 generated successfully')).toBe('184875929281435')
  })
  it.each(['', 'Latest version: 999', 'Version generated: 100\nVersion generated: 200'])('refuses absent or ambiguous output', (output) => {
    expect(() => parse_commit_version(output)).toThrow('one unambiguous version')
  })

  it.each([false, true])('isolates source and credentials, and cleans the temporary project (failure=%s)', async (failure) => {
    const config = load_publish_config({ NODE_ENV: 'development', ALIYUN_ESA_PUBLISH_ACCESS_KEY_ID: 'selected-id', ALIYUN_ESA_PUBLISH_ACCESS_KEY_SECRET: 'selected-secret' })
    vi.stubEnv('ESA_ACCESS_KEY_ID', 'wrong-inherited-id')
    vi.stubEnv('JWT_SECRET', 'unrelated-app-secret')
    const source = Buffer.from('export default { /* test snapshot */ }')
    let directory = ''
    const end = vi.fn()
    exec.mockImplementation((_node: string, args: string[], options: ExecFileOptions, callback: (error: Error | null, stdout: string, stderr: string) => void) => {
      directory = String(options.cwd)
      expect(args[0]).toMatch(/esa-cli[/\\]dist[/\\]index.js$/)
      expect(args).toContain('--no-bundle')
      expect(args).toContain('--skip-update-check')
      expect(args[args.indexOf('--name') + 1]).toBe(config.name)
      expect(args[args.indexOf('--environment') + 1]).toBe('production')
      expect(JSON.stringify(args)).not.toContain('selected-secret')
      expect(options).toMatchObject({ windowsHide: true, timeout: config.readinessTimeoutMs })
      expect(options.env).toMatchObject({ ESA_ACCESS_KEY_ID: 'selected-id', ESA_ACCESS_KEY_SECRET: 'selected-secret' })
      expect(options.env).not.toHaveProperty('JWT_SECRET')
      expect(readdirSync(directory).sort()).toEqual(['entry.mjs', 'esa.jsonc'])
      expect(readFileSync(join(directory, 'entry.mjs'))).toEqual(source)
      expect(JSON.parse(readFileSync(join(directory, 'esa.jsonc'), 'utf8'))).toEqual({ name: config.name, entry: './entry.mjs' })
      callback(failure ? new Error('SDK diagnostic contains selected-secret') : null, 'Version generated: 12345', 'selected-secret')
      return { stdin: { end } }
    })
    if (failure) {
      const error = await commit_source(config, source, 'test-description').catch(error => error as Error)
      expect(String(error)).toContain('commit failed or timed out')
      expect(String(error)).not.toContain('selected-secret')
    }
    else {
      expect(await commit_source(config, source, 'test-description')).toBe('12345')
    }
    expect(end).toHaveBeenCalledOnce()
    expect(existsSync(directory)).toBe(false)
  })
})
